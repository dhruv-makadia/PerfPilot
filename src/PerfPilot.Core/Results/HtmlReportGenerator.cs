using System.Globalization;
using System.Net;
using System.Text;
using PerfPilot.Core.Domain;
using PerfPilot.Core.Services;

namespace PerfPilot.Core.Results;

/// <summary>
/// Renders a run as a single self-contained HTML file (inline CSS and SVG charts, no scripts or external assets)
/// so it can be attached to tickets or emailed and opened offline.
/// </summary>
public sealed class HtmlReportGenerator(TimeProvider clock)
{
    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    public string Generate(TestRun run)
    {
        var sb = new StringBuilder(32 * 1024);
        var title = $"PerfPilot report – {run.ScenarioName}";
        sb.Append("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n");
        sb.Append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
        sb.Append("<title>").Append(E(title)).Append("</title>\n<style>\n").Append(Css).Append("</style>\n</head>\n<body>\n<main>\n");

        WriteHeader(sb, run);
        WriteVerdict(sb, run);
        WriteCards(sb, run);
        WriteThresholds(sb, run);
        WriteEndpoints(sb, run);
        WriteCharts(sb, run);
        WriteConfiguration(sb, run);

        sb.Append("<footer>Generated by PerfPilot on ").Append(E(clock.GetUtcNow().ToString("yyyy-MM-dd HH:mm:ss 'UTC'", Inv)))
          .Append(". Load generated by k6.</footer>\n");
        sb.Append("</main>\n</body>\n</html>\n");
        return sb.ToString();
    }

    private static void WriteHeader(StringBuilder sb, TestRun run)
    {
        sb.Append("<header>\n<div class=\"brand\">PerfPilot</div>\n<h1>").Append(E(run.ScenarioName)).Append("</h1>\n");
        sb.Append("<div class=\"meta\">\n");
        Meta(sb, "Environment", E(run.EnvironmentName) + (run.EnvironmentIsProduction ? " <span class=\"badge prod\">PRODUCTION</span>" : ""));
        Meta(sb, "Base URL", E(run.EnvironmentBaseUrl));
        Meta(sb, "Started by", E(run.StartedBy));
        Meta(sb, "Started", E(FormatTime(run.StartedAt)));
        Meta(sb, "Ended", E(FormatTime(run.EndedAt)));
        Meta(sb, "Duration", run.StartedAt is { } s && run.EndedAt is { } e ? E(DurationParser.Format(e - s)) : "–");
        Meta(sb, "Status", E(run.Status.ToString()));
        Meta(sb, "Run ID", $"<code>{run.Id}</code>");
        sb.Append("</div>\n</header>\n");
    }

    private static void Meta(StringBuilder sb, string label, string html) =>
        sb.Append("<div><span>").Append(E(label)).Append("</span><strong>").Append(html).Append("</strong></div>\n");

    private static void WriteVerdict(StringBuilder sb, TestRun run)
    {
        var (css, heading, detail) = run.Status switch
        {
            RunStatus.Completed when run.ThresholdsPassed == true => ("pass", "PASSED", run.ThresholdResults.Count == 0
                ? "The run completed. No SLA thresholds were defined."
                : $"All {run.ThresholdResults.Count} SLA threshold(s) were met."),
            RunStatus.Completed => ("fail", "FAILED", $"{run.ThresholdResults.Count(t => !t.Passed)} of {run.ThresholdResults.Count} SLA threshold(s) were breached."),
            RunStatus.Cancelled => ("warn", "CANCELLED", $"Cancelled{(run.CancelledBy is null ? "" : " by " + run.CancelledBy)}. Results cover the portion that ran."),
            RunStatus.Failed => ("fail", "ERROR", run.ErrorMessage ?? "The run failed."),
            _ => ("warn", run.Status.ToString().ToUpperInvariant(), "The run has not finished yet."),
        };
        sb.Append("<section class=\"verdict ").Append(css).Append("\"><div class=\"verdict-title\">").Append(E(heading))
          .Append("</div><div>").Append(E(detail)).Append("</div></section>\n");
    }

    private static void WriteCards(StringBuilder sb, TestRun run)
    {
        var o = run.Overall;
        sb.Append("<section class=\"cards\">\n");
        Card(sb, "Requests", o.Count.ToString("N0", Inv));
        Card(sb, "Throughput", $"{o.Rps.ToString("0.##", Inv)} req/s");
        Card(sb, "Avg latency", Ms(o.AvgMs));
        Card(sb, "p95 latency", Ms(o.P95Ms));
        Card(sb, "p99 latency", Ms(o.P99Ms));
        Card(sb, "Error rate", Pct(o.ErrorRate));
        var totalChecks = run.ChecksPassed + run.ChecksFailed;
        Card(sb, "Status checks", totalChecks == 0 ? "–" : $"{Pct((double)run.ChecksPassed / totalChecks)} passed");
        sb.Append("</section>\n");
    }

    private static void Card(StringBuilder sb, string label, string value) =>
        sb.Append("<div class=\"card\"><span>").Append(E(label)).Append("</span><strong>").Append(E(value)).Append("</strong></div>\n");

    private static void WriteThresholds(StringBuilder sb, TestRun run)
    {
        sb.Append("<section>\n<h2>SLA thresholds</h2>\n");
        if (run.ThresholdResults.Count == 0)
        {
            sb.Append("<p class=\"muted\">No SLA thresholds were defined for this scenario.</p>\n</section>\n");
            return;
        }
        sb.Append("<table>\n<thead><tr><th>Scope</th><th>Metric</th><th class=\"num\">Limit</th><th class=\"num\">Actual</th><th>Result</th></tr></thead>\n<tbody>\n");
        foreach (var t in run.ThresholdResults.OrderBy(t => t.SortOrder))
        {
            sb.Append("<tr class=\"").Append(t.Passed ? "" : "breach").Append("\"><td>").Append(E(t.ScopeName)).Append("</td><td>")
              .Append(E(MetricLabel(t.Metric))).Append("</td><td class=\"num\">").Append(E(FormatSla(t.Metric, t.Limit, true)))
              .Append("</td><td class=\"num\">").Append(E(t.Actual is { } a ? FormatSla(t.Metric, a, false) : "no data"))
              .Append("</td><td>").Append(t.Passed ? "<span class=\"badge ok\">PASS</span>" : "<span class=\"badge bad\">FAIL</span>")
              .Append("</td></tr>\n");
        }
        sb.Append("</tbody>\n</table>\n</section>\n");
    }

    private static void WriteEndpoints(StringBuilder sb, TestRun run)
    {
        sb.Append("<section>\n<h2>Endpoints</h2>\n");
        if (run.EndpointResults.Count == 0)
        {
            sb.Append("<p class=\"muted\">No endpoint results were recorded.</p>\n</section>\n");
            return;
        }

        var breaches = run.ThresholdResults.Where(t => !t.Passed && t.EndpointKey is not null)
            .GroupBy(t => t.EndpointKey!)
            .ToDictionary(g => g.Key, g => g.Select(t => t.Metric).ToHashSet());

        sb.Append("<div class=\"scroll\"><table>\n<thead><tr><th>Endpoint</th><th class=\"num\">Requests</th><th class=\"num\">RPS</th><th class=\"num\">Avg</th>")
          .Append("<th class=\"num\">p50</th><th class=\"num\">p90</th><th class=\"num\">p95</th><th class=\"num\">p99</th><th class=\"num\">Max</th><th class=\"num\">Errors</th></tr></thead>\n<tbody>\n");
        foreach (var ep in run.EndpointResults.OrderBy(e => e.SortOrder))
        {
            var b = breaches.GetValueOrDefault(ep.Key) ?? [];
            var m = ep.Metrics;
            sb.Append("<tr><td><span class=\"method m-").Append(E(ep.Method.ToLowerInvariant())).Append("\">").Append(E(ep.Method)).Append("</span> ")
              .Append(E(ep.Name == $"{ep.Method} {ep.Path}" ? ep.Path : ep.Name)).Append("</td>");
            Cell(sb, m.Count.ToString("N0", Inv), false);
            Cell(sb, m.Rps.ToString("0.##", Inv), b.Contains(SlaMetric.MinRps));
            Cell(sb, Ms(m.AvgMs), false);
            Cell(sb, Ms(m.P50Ms), false);
            Cell(sb, Ms(m.P90Ms), false);
            Cell(sb, Ms(m.P95Ms), b.Contains(SlaMetric.P95));
            Cell(sb, Ms(m.P99Ms), b.Contains(SlaMetric.P99));
            Cell(sb, Ms(m.MaxMs), false);
            Cell(sb, Pct(m.ErrorRate), b.Contains(SlaMetric.ErrorRate));
            sb.Append("</tr>\n");
        }
        sb.Append("</tbody>\n</table></div>\n<p class=\"muted\">Highlighted cells breached an endpoint SLA.</p>\n</section>\n");
    }

    private static void Cell(StringBuilder sb, string value, bool breach) =>
        sb.Append("<td class=\"num").Append(breach ? " breach-cell" : "").Append("\">").Append(E(value)).Append("</td>");

    private static void WriteCharts(StringBuilder sb, TestRun run)
    {
        sb.Append("<section>\n<h2>Over time</h2>\n");
        var series = run.TimeSeries;
        if (series.Count < 2)
        {
            sb.Append("<p class=\"muted\">Not enough samples to draw charts.</p>\n</section>\n");
            return;
        }
        var t = series.Select(p => p.T).ToArray();
        // Buckets without requests have no latency/error rate: emit gaps rather than misleading zeros.
        double?[] WhenRequests(Func<TimeSeriesPoint, double> value) => series.Select(p => p.Requests > 0 ? value(p) : (double?)null).ToArray();
        sb.Append("<div class=\"chart\"><h3>Latency percentiles (ms)</h3>")
          .Append(SvgChart(t, [("p50", "#2563eb", WhenRequests(p => p.P50Ms)), ("p95", "#f59e0b", WhenRequests(p => p.P95Ms)), ("p99", "#dc2626", WhenRequests(p => p.P99Ms))], "ms"))
          .Append("</div>\n");
        sb.Append("<div class=\"chart\"><h3>Throughput (req/s) and virtual users</h3>")
          .Append(SvgChart(t, [("RPS", "#059669", series.Select(p => (double?)p.Rps).ToArray()), ("VUs", "#7c3aed", series.Select(p => (double?)p.Vus).ToArray())], ""))
          .Append("</div>\n");
        sb.Append("<div class=\"chart\"><h3>Error rate (%)</h3>")
          .Append(SvgChart(t, [("Error rate", "#dc2626", WhenRequests(p => p.ErrorRate * 100))], "%"))
          .Append("</div>\n</section>\n");
    }

    private static string SvgChart(double[] x, (string Name, string Color, double?[] Values)[] lines, string unit)
    {
        const int width = 900, height = 240, left = 56, right = 16, top = 16, bottom = 36;
        var plotW = width - left - right;
        var plotH = height - top - bottom;
        var maxX = Math.Max(x.Max(), 1);
        var maxY = lines.SelectMany(l => l.Values).Where(v => v.HasValue).Select(v => v!.Value).DefaultIfEmpty(0).Max();
        maxY = maxY <= 0 ? 1 : NiceCeiling(maxY * 1.1);

        var svg = new StringBuilder();
        svg.Append("<svg viewBox=\"0 0 ").Append(width).Append(' ').Append(height).Append("\" role=\"img\" preserveAspectRatio=\"none\">");
        for (var i = 0; i <= 4; i++)
        {
            var yVal = maxY * i / 4;
            var y = top + plotH - plotH * i / 4.0;
            svg.Append("<line x1=\"").Append(left).Append("\" x2=\"").Append(width - right).Append("\" y1=\"").Append(F(y)).Append("\" y2=\"").Append(F(y))
               .Append("\" class=\"grid\"/>");
            svg.Append("<text x=\"").Append(left - 6).Append("\" y=\"").Append(F(y + 4)).Append("\" class=\"axis\" text-anchor=\"end\">")
               .Append(E(yVal.ToString(yVal >= 100 ? "0" : "0.#", Inv) + unit)).Append("</text>");
        }
        for (var i = 0; i <= 5; i++)
        {
            var xVal = maxX * i / 5;
            var xp = left + plotW * i / 5.0;
            svg.Append("<text x=\"").Append(F(xp)).Append("\" y=\"").Append(height - 12).Append("\" class=\"axis\" text-anchor=\"middle\">")
               .Append(E(DurationParser.Format(TimeSpan.FromSeconds(xVal)))).Append("</text>");
        }
        foreach (var (name, color, values) in lines)
        {
            // One polyline per run of consecutive values, so missing points break the line.
            var segment = new StringBuilder();
            void Flush()
            {
                if (segment.Length > 0)
                {
                    svg.Append("<polyline fill=\"none\" stroke=\"").Append(color).Append("\" stroke-width=\"2\" points=\"").Append(segment)
                       .Append("\"><title>").Append(E(name)).Append("</title></polyline>");
                    segment.Clear();
                }
            }
            for (var i = 0; i < x.Length && i < values.Length; i++)
            {
                if (values[i] is not { } value)
                {
                    Flush();
                    continue;
                }
                var px = left + plotW * (x[i] / maxX);
                var py = top + plotH - plotH * (value / maxY);
                segment.Append(F(px)).Append(',').Append(F(py)).Append(' ');
            }
            Flush();
        }
        svg.Append("</svg><div class=\"legend\">");
        foreach (var (name, color, _) in lines)
        {
            svg.Append("<span><i style=\"background:").Append(color).Append("\"></i>").Append(E(name)).Append("</span>");
        }
        svg.Append("</div>");
        return svg.ToString();
    }

    private static double NiceCeiling(double value)
    {
        var magnitude = Math.Pow(10, Math.Floor(Math.Log10(value)));
        var normalized = value / magnitude;
        var nice = normalized <= 1 ? 1 : normalized <= 2 ? 2 : normalized <= 2.5 ? 2.5 : normalized <= 5 ? 5 : 10;
        return nice * magnitude;
    }

    private static void WriteConfiguration(StringBuilder sb, TestRun run)
    {
        var def = run.ScenarioSnapshot;
        var profile = def.LoadProfile;
        sb.Append("<section>\n<h2>Configuration</h2>\n<div class=\"two-col\">\n<div>\n<h3>Load profile: ").Append(E(profile.Preset.ToString())).Append("</h3>\n");
        sb.Append("<table><thead><tr><th>Stage</th><th>Duration</th><th class=\"num\">Target VUs</th></tr></thead><tbody>\n");
        for (var i = 0; i < profile.Stages.Count; i++)
        {
            sb.Append("<tr><td>").Append(i + 1).Append("</td><td>").Append(E(profile.Stages[i].Duration)).Append("</td><td class=\"num\">")
              .Append(profile.Stages[i].Target).Append("</td></tr>\n");
        }
        sb.Append("</tbody></table>\n<p class=\"muted\">Think time ").Append(E(profile.ThinkTimeMinSeconds.ToString("0.##", Inv))).Append("–")
          .Append(E(profile.ThinkTimeMaxSeconds.ToString("0.##", Inv))).Append(" s between requests.</p>\n</div>\n<div>\n<h3>Traffic mix</h3>\n");
        sb.Append("<table><thead><tr><th>Endpoint</th><th class=\"num\">Weight</th><th>Expected</th></tr></thead><tbody>\n");
        foreach (var ep in def.Endpoints)
        {
            sb.Append("<tr><td>").Append(E(ep.DisplayName)).Append("</td><td class=\"num\">").Append(E(ep.Weight.ToString("0.##", Inv))).Append("%</td><td>")
              .Append(E(string.Join(", ", ep.ExpectedStatusCodes))).Append("</td></tr>\n");
        }
        sb.Append("</tbody></table>\n</div>\n</div>\n</section>\n");
    }

    private static string MetricLabel(SlaMetric metric) => metric switch
    {
        SlaMetric.P95 => "p95 latency",
        SlaMetric.P99 => "p99 latency",
        SlaMetric.ErrorRate => "Error rate",
        SlaMetric.MinRps => "Throughput",
        _ => metric.ToString(),
    };

    private static string FormatSla(SlaMetric metric, double value, bool isLimit) => metric switch
    {
        SlaMetric.P95 or SlaMetric.P99 => (isLimit ? "≤ " : "") + Ms(value),
        SlaMetric.ErrorRate => (isLimit ? "≤ " : "") + value.ToString("0.##", Inv) + "%",
        SlaMetric.MinRps => (isLimit ? "≥ " : "") + value.ToString("0.##", Inv) + " req/s",
        _ => value.ToString(Inv),
    };

    private static string Ms(double ms) => ms >= 1000 ? (ms / 1000).ToString("0.00", Inv) + " s" : ms.ToString("0.#", Inv) + " ms";
    private static string Pct(double ratio) => (ratio * 100).ToString("0.##", Inv) + "%";
    private static string F(double v) => v.ToString("0.#", Inv);
    private static string E(string? value) => WebUtility.HtmlEncode(value ?? string.Empty);
    private static string FormatTime(DateTimeOffset? t) => t?.ToUniversalTime().ToString("yyyy-MM-dd HH:mm:ss 'UTC'", Inv) ?? "–";

